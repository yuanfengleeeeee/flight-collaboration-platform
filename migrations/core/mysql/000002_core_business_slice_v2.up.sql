CREATE TABLE IF NOT EXISTS task_template (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) NOT NULL,
    name VARCHAR(255) NOT NULL,
    trigger_type VARCHAR(64) NOT NULL,
    template_version INT UNSIGNED NOT NULL,
    enabled TINYINT(1) NOT NULL DEFAULT 1,
    target_area_id BIGINT UNSIGNED NOT NULL,
    target_team_id BIGINT UNSIGNED NOT NULL,
    required_position_code VARCHAR(64) NOT NULL,
    required_capabilities JSON NOT NULL,
    planned_offset_seconds INT NOT NULL DEFAULT 0,
    default_message TEXT NOT NULL,
    created_by_public_id CHAR(36) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_task_template_public_id (public_id),
    UNIQUE KEY uk_task_template_trigger_version (trigger_type, template_version),
    KEY idx_task_template_trigger_enabled (trigger_type, enabled),
    KEY idx_task_template_team (target_team_id, enabled),
    CONSTRAINT fk_task_template_area FOREIGN KEY (target_area_id) REFERENCES operation_area (id),
    CONSTRAINT fk_task_template_team FOREIGN KEY (target_team_id) REFERENCES team (id),
    CONSTRAINT chk_task_template_enabled CHECK (enabled IN (0, 1)),
    CONSTRAINT chk_task_template_offset CHECK (planned_offset_seconds >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS task_instance (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) NOT NULL,
    flight_id BIGINT UNSIGNED NOT NULL,
    template_id BIGINT UNSIGNED NOT NULL,
    area_id BIGINT UNSIGNED NOT NULL,
    team_id BIGINT UNSIGNED NOT NULL,
    trigger_type VARCHAR(64) NOT NULL,
    generation_key VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    source_event_id VARCHAR(128) NOT NULL,
    template_version INT UNSIGNED NOT NULL,
    task_name VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    planned_at DATETIME(6) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'awaiting_confirmation',
    status_version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    sync_version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    completed_at DATETIME(6) NULL,
    cancelled_at DATETIME(6) NULL,
    cancel_reason VARCHAR(255) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_task_instance_public_id (public_id),
    UNIQUE KEY uk_task_instance_generation_key (generation_key),
    KEY idx_task_instance_flight (flight_id),
    KEY idx_task_instance_team_status (team_id, status, planned_at),
    KEY idx_task_instance_source_event (source_event_id),
    CONSTRAINT fk_task_instance_flight FOREIGN KEY (flight_id) REFERENCES flight (id),
    CONSTRAINT fk_task_instance_template FOREIGN KEY (template_id) REFERENCES task_template (id),
    CONSTRAINT fk_task_instance_area FOREIGN KEY (area_id) REFERENCES operation_area (id),
    CONSTRAINT fk_task_instance_team FOREIGN KEY (team_id) REFERENCES team (id),
    CONSTRAINT chk_task_instance_status CHECK (status IN ('awaiting_confirmation', 'assigned', 'in_progress', 'completed', 'cancelled'))
