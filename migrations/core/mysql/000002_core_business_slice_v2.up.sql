CREATE TABLE IF NOT EXISTS operation_area (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) NOT NULL,
    code VARCHAR(64) NOT NULL,
    name VARCHAR(128) NOT NULL,
    enabled TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_operation_area_public_id (public_id),
    UNIQUE KEY uk_operation_area_code (code),
    CONSTRAINT chk_operation_area_enabled CHECK (enabled IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS team (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) NOT NULL,
    area_id BIGINT UNSIGNED NOT NULL,
    code VARCHAR(64) NOT NULL,
    name VARCHAR(128) NOT NULL,
    enabled TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_team_public_id (public_id),
    UNIQUE KEY uk_team_area_code (area_id, code),
    KEY idx_team_area_enabled (area_id, enabled),
    CONSTRAINT fk_team_area FOREIGN KEY (area_id) REFERENCES operation_area (id),
    CONSTRAINT chk_team_enabled CHECK (enabled IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS personnel (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) NOT NULL,
    user_public_id CHAR(36) NOT NULL,
    employee_no VARCHAR(64) NOT NULL,
    display_name VARCHAR(128) NOT NULL,
    team_id BIGINT UNSIGNED NOT NULL,
    position_code VARCHAR(64) NOT NULL,
    capabilities JSON NOT NULL,
    work_state VARCHAR(32) NOT NULL DEFAULT 'idle',
    status_version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    last_state_changed_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    unavailable_reason VARCHAR(255) NULL,
    enabled TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_personnel_public_id (public_id),
    UNIQUE KEY uk_personnel_user_public_id (user_public_id),
    UNIQUE KEY uk_personnel_employee_no (employee_no),
    KEY idx_personnel_team_state (team_id, work_state, enabled),
    KEY idx_personnel_state_changed (work_state, last_state_changed_at),
    CONSTRAINT fk_personnel_team FOREIGN KEY (team_id) REFERENCES team (id),
    CONSTRAINT chk_personnel_work_state CHECK (work_state IN ('idle', 'reserved', 'busy', 'unavailable')),
    CONSTRAINT chk_personnel_enabled CHECK (enabled IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS team_member (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) NOT NULL,
    team_id BIGINT UNSIGNED NOT NULL,
    personnel_id BIGINT UNSIGNED NOT NULL,
    is_primary TINYINT(1) NOT NULL DEFAULT 1,
    joined_at DATETIME(6) NOT NULL,
    left_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_team_member_public_id (public_id),
    UNIQUE KEY uk_team_member_period (team_id, personnel_id, joined_at),
    KEY idx_team_member_personnel (personnel_id, left_at),
    KEY idx_team_member_team (team_id, left_at),
    CONSTRAINT fk_team_member_team FOREIGN KEY (team_id) REFERENCES team (id),
    CONSTRAINT fk_team_member_personnel FOREIGN KEY (personnel_id) REFERENCES personnel (id),
    CONSTRAINT chk_team_member_primary CHECK (is_primary IN (0, 1)),
    CONSTRAINT chk_team_member_period CHECK (left_at IS NULL OR left_at >= joined_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

